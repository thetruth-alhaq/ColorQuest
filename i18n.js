/* ================= engine ================= */
(function () {
  const RTL_CODES = { ar: 1, ur: 1 };

  function pick() {
    const q = new URLSearchParams(location.search).get("lang");
    const saved = localStorage.getItem("cq_lang");
    const nav = (navigator.language || "en").replace("-", "_");
    return (q && CQ_T[q]) ? q : (saved && CQ_T[saved]) ? saved
         : CQ_T[nav] ? nav : CQ_T[nav.split("_")[0]] ? nav.split("_")[0] : "en";
  }

  function apply(code) {
    const t = CQ_T[code];
    document.documentElement.lang = code.replace("_", "-");
    document.documentElement.dir = RTL_CODES[code] ? "rtl" : "ltr";
    document.title = t._meta || document.title;
    const mt = document.querySelector('meta[name="description"]');
    if (mt && t.hero_sub) mt.setAttribute("content", t.hero_sub);
    document.querySelectorAll("[data-i18n]").forEach(el => {
      const k = el.getAttribute("data-i18n");
      if (t[k] !== undefined) el.textContent = t[k];
    });
    document.querySelectorAll("[data-i18n-html]").forEach(el => {
      const k = el.getAttribute("data-i18n-html");
      if (t[k] !== undefined) el.innerHTML = t[k];
    });
    // array values (game chips)
    document.querySelectorAll("[data-i18n-chips]").forEach(el => {
      const k = el.getAttribute("data-i18n-chips");
      if (Array.isArray(t[k])) {
        el.innerHTML = "";
        t[k].forEach(name => {
          const s = document.createElement("span");
          s.className = "chip";
          s.textContent = name;
          el.appendChild(s);
        });
      }
    });
    // mark active in menu
    document.querySelectorAll("#langMenu button").forEach(b =>
      b.classList.toggle("active", b.dataset.lang === code));
    const btn = document.getElementById("langBtn");
    if (btn) {
      const L = CQ_LANGS.find(l => l.code === code);
      btn.innerHTML = "🌐 " + (L ? L.flag + " " + L.name : code);
    }
    localStorage.setItem("cq_lang", code);
  }

  function buildMenu() {
    const menu = document.getElementById("langMenu");
    if (!menu) return;
    CQ_LANGS.forEach(l => {
      const b = document.createElement("button");
      b.type = "button";
      b.dataset.lang = l.code;
      b.dir = "auto";
      b.innerHTML = '<span class="flag">' + l.flag + '</span><span>' + l.name + "</span>";
      b.addEventListener("click", () => { apply(l.code); menu.classList.remove("open"); });
      menu.appendChild(b);
    });
    const btn = document.getElementById("langBtn");
    if (btn) btn.addEventListener("click", e => {
      e.stopPropagation();
      menu.classList.toggle("open");
    });
    document.addEventListener("click", e => {
      if (!e.target.closest(".lang-wrap")) menu.classList.remove("open");
    });
  }

  document.addEventListener("DOMContentLoaded", () => { buildMenu(); apply(pick()); });
})();
